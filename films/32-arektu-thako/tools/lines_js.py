"""lines.json (sung lines, timed from the master) + tools/en.json (free English) -> js/lines.js for the page."""
import json, os
D = os.path.dirname(os.path.abspath(__file__)) + '/../'
L = json.load(open(D + 'lines.json')); E = json.load(open(D + 'tools/en.json'))
assert len(L) == len(E), (len(L), len(E))
out = [{'t0': l['t0'], 't1': l['t1'], 'bn': l['text'], 'en': e} for l, e in zip(L, E)]
open(D + 'js/lines.js', 'w').write('// generated by tools/lines_js.py: the sung lines with their times in the master\nexport const LINES = ' + json.dumps(out, ensure_ascii=False, indent=0) + ';\n')
print(len(out), 'lines')
